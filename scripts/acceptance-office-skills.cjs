'use strict';

// Generate real Office files with the bundled Hermes Python runtime. This is
// intentionally a small format smoke, not a fake placeholder artifact.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const output = path.resolve(process.env.AIBOX_OFFICE_OUTPUT || path.join(root, 'tmp', 'acceptance-office-skills', new Date().toISOString().replace(/[:.]/g, '-')));
fs.mkdirSync(output, { recursive: true });
const python = process.platform === 'win32' ? path.join(root, 'runtime', 'hermes', 'python', 'python.exe') : path.join(root, 'runtime', 'hermes', 'python', 'bin', 'python3');
const script = String.raw`
from pathlib import Path
import sys
from docx import Document
from openpyxl import Workbook
from pptx import Presentation
from pptx.util import Inches

out = Path(sys.argv[1])
doc = Document()
doc.add_heading('OPC-Nexus Office Skill Smoke', level=1)
doc.add_paragraph('Real DOCX generated by the bundled Hermes runtime.')
doc.save(out / 'office-smoke.docx')

book = Workbook()
sheet = book.active
sheet.title = 'Smoke'
sheet.append(['artifact', 'status'])
sheet.append(['xlsx', 'generated'])
book.save(out / 'office-smoke.xlsx')

deck = Presentation()
slide = deck.slides.add_slide(deck.slide_layouts[1])
slide.shapes.title.text = 'OPC-Nexus Office Skill Smoke'
slide.placeholders[1].text = 'Real PPTX generated by the bundled Hermes runtime.'
deck.save(out / 'office-smoke.pptx')
`;
execFileSync(python, ['-c', script, output], { cwd: root, stdio: 'inherit', windowsHide: true });
const files = ['office-smoke.docx', 'office-smoke.xlsx', 'office-smoke.pptx'].map((name) => {
  const file = path.join(output, name);
  const bytes = fs.readFileSync(file);
  return { name, path: file, bytes: bytes.byteLength, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), zipSignature: bytes.subarray(0, 2).toString('hex') === '504b' };
});
const report = { generatedAt: new Date().toISOString(), python, output, files, result: files.every((file) => file.bytes > 0 && file.zipSignature) ? 'PASS' : 'BLOCKED' };
fs.writeFileSync(path.join(output, 'report.json'), `${JSON.stringify(report, null, 2)}\n`, 'utf8');
process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
if (report.result !== 'PASS') process.exitCode = 2;
